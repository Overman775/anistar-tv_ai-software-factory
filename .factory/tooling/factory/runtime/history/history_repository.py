"""Verified access to historical runs and their original artifacts."""

from pathlib import Path
from typing import Protocol

from factory.runtime.contracts import State


class HistoryRepository(Protocol):
    def current(self, root: Path) -> State: ...
    def archived_state(self, root: Path, run: str) -> State: ...
    def stored_evidence(
        self, root: Path, run: str, name: str, *, allow_loose: bool
    ) -> bytes | None: ...
    def listing(self, root: Path, run: str) -> list[dict[str, object]]: ...
    def export(self, root: Path, run: str, name: str, output: Path) -> None: ...
    def verify_history(self, root: Path, run: str, *, bind: bool) -> int: ...
    def visible(self, root: Path, run: str, workspace: str) -> bool: ...
